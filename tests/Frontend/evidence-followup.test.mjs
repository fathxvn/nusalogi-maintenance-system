import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import test from 'node:test';
import { renderToStaticMarkup } from 'react-dom/server';
import { configure, findElement, loadComponent } from './component-harness.mjs';
const { TicketEvidenceForm: TicketForm } = await import(loadComponent(resolve('resources/js/components/ticket-evidence-form.tsx')));
const { ReportEvidenceDetachForm: DetachForm } = await import(loadComponent(resolve('resources/js/components/report-evidence-detach-form.tsx')));
const action = { url: '/evidence', command_key: '11111111-1111-4111-8111-111111111111', upload_key: '22222222-2222-4222-8222-222222222222' };
const event = { preventDefault() {} };
const formIn = tree => findElement(tree, node => node.type === 'form');
test('ticket evidence waits for digest, submits scoped multipart with observed version and no approval decision', () => {
    const form = configure();
    const props = { action, ticketVersion: 4, refreshUrl: '/ticket' };
    formIn(TicketForm(props)).props.onSubmit(event);
    assert.equal(form.calls.length, 0);
    form.setData('file', { name: 'proof.pdf' });
    form.setData('sha256', 'a'.repeat(64));
    const tree = TicketForm(props);
    const purpose = findElement(tree, node => node.type === 'select');
    purpose.props.onChange({ target: { value: 'authorization' } });
    formIn(tree).props.onSubmit(event);
    formIn(tree).props.onSubmit(event);
    assert.equal(form.calls.length, 1);
    assert.equal(form.data.expected_ticket_version, 4);
    assert.equal(form.data.purpose, 'authorization');
    assert.equal(form.data.decision, undefined);
    assert.equal(form.data.upload_key, action.upload_key);
    assert.equal(form.calls[0][2].forceFormData, true);
    assert.equal(form.calls[0][2].preserveState, 'errors');
    assert.ok(renderToStaticMarkup(tree).includes('persetujuan operasional dicatat terpisah'));
});
test('detaching draft evidence requires a reason and preserves key/version across retry', () => {
    const form = configure();
    const props = { action, reportVersion: 5, photoId: 7, refreshUrl: '/report' };
    const empty = DetachForm(props);
    formIn(empty).props.onSubmit(event);
    assert.equal(form.calls.length, 0);
    form.setData('reason', 'Salah lampiran');
    const ready = DetachForm(props);
    formIn(ready).props.onSubmit(event);
    formIn(ready).props.onSubmit(event);
    assert.equal(form.calls.length, 1);
    assert.equal(form.calls[0][0], 'delete');
    assert.equal(form.calls[0][2].preserveState, 'errors');
    assert.equal(form.data.expected_report_version, 5);
    assert.equal(form.data.command_key, action.command_key);
    assert.ok(renderToStaticMarkup(ready).includes('revisi lama tetap tersimpan'));
});
